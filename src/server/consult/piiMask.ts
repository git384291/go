/**
 * AI에 보내기 전 개인정보 가림(PM 11/21 6항). 고객 글에서 연락처·이메일·주민번호·주소·이름 표현을 지운 글만 모델에 간다.
 * 이 가림은 '추가 방어'다. 접수 양식 값(이름·전화)은 애초에 이 경로로 들어오지 않고, 모델 입력은 가린 글 + 승인 견적 문장뿐이다.
 */
const RULES: readonly [RegExp, string][] = [
  [/[\w.+-]+@[\w-]+(\.[\w-]+)+/g, '[이메일]'],
  [/\d{6}\s*-?\s*[1-8]\d{6}/g, '[주민번호]'],
  [/0\d{1,2}\s*[-.)]?\s*\d{3,4}\s*[-.]?\s*\d{4}/g, '[전화]'],
  [/(이름은?|성함은?|저는)\s*[가-힣]{2,4}/g, '$1 [이름]'],
  [/[가-힣0-9]+(로|길)\s*\d+(-\d+)?(\s*번?길)?(\s*\d+호)?/g, '[주소]'],
  [/[가-힣0-9]+(동|리)\s*\d+(-\d+)?\s*(번지)?/g, '[주소]'],
  [/\d{7,}/g, '[번호]'],
];
export function maskPii(text: string): string {
  let out = text;
  for (const [re, to] of RULES) out = out.replace(re, to);
  return out;
}
