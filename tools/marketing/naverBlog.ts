// ─── 포스팅 → 텍스트 변환 (복붙용) ──────────────────────────────────────────

export function renderPost(post: BlogPost): string {
  const header = `[제목]\n${post.title}\n\n[태그]\n${post.tags.join(', ')}\n\n${'─'.repeat(60)}\n\n`;
  const body = post.sections
    .map(s => `## ${s.heading}\n\n${s.content}`)
    .join('\n\n---\n\n');
  return header + body;
}

export function renderAllPosts(): string {
  return BLOG_POSTS.map((p, i) =>
    `\n${'='.repeat(60)}\n포스팅 ${i + 1}/${BLOG_POSTS.length}\n${'='.repeat(60)}\n\n${renderPost(p)}`
  ).join('\n\n');
}
